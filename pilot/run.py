"""Run A once against real distance-matrix correctness and timing checks."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import secrets
import shutil
from datetime import datetime, timezone

from library import Library
from research_agent.io import atomic_json, read_json, read_jsonl
from research_agent.runner import TaskRunner

from .harness import PilotHarness, TASK_ID, WORKSPACE
from .ledger import PilotLedger
from .roles import ScriptedRoles


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def run_pilot(*, size: int = 2500, repetitions: int = 7, run_dir: Path | None = None) -> dict:
    if run_dir is None:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
        run_dir = PROJECT_ROOT / "runs" / f"pilot-{stamp}-{secrets.token_hex(2)}"
    run_dir = Path(run_dir).resolve()
    if run_dir.exists():
        raise FileExistsError(run_dir)
    run_dir.mkdir(parents=True)
    baseline_dir = run_dir / "tasks" / TASK_ID / "nodes" / "n0000"
    baseline_dir.mkdir(parents=True)
    shutil.copyfile(WORKSPACE / "original.py", baseline_dir / "solution.py")
    harness = PilotHarness(size=size, repetitions=repetitions, measurements_path=run_dir / "measurements.jsonl")
    baseline = harness.score(TASK_ID, baseline_dir, "dev")
    if not baseline["ok"] or not baseline["correct"]:
        raise RuntimeError(f"Pilot baseline scoring failed: {baseline['error']}")
    ledger = PilotLedger(run_dir, TASK_ID)
    library = Library.open(run_dir / "library")
    roles = ScriptedRoles(PROJECT_ROOT / "pilot" / "candidate.py")
    outcome = TaskRunner(
        run_dir=run_dir, task_id=TASK_ID, harness=harness, ledger=ledger,
        roles=roles, library=library, baseline_score=baseline,
        config=read_json(PROJECT_ROOT / "config" / "agent.json", "agent/1"),
        hard_caps=read_json(PROJECT_ROOT / "config" / "hard_caps.json", "hard_caps/1"),
    ).run()
    measurements = read_jsonl(run_dir / "measurements.jsonl", "pilot_measurement/1")
    candidate = next((m for m in measurements if m["node_dir"].endswith("/n0001")), None)
    reference_speedup = (candidate["medians"]["original"] / candidate["medians"]["reference"]) if candidate else None
    report = {
        "schema": "pilot_report/1", "run_id": run_dir.name, "task_id": TASK_ID,
        "run_dir": str(run_dir), "input_size": size, "repetitions": repetitions,
        "baseline_score": baseline["score"], "best_node": outcome.best_node,
        "best_dev_score": outcome.dev_score, "experiments": outcome.experiments,
        "correct": candidate is not None,
        "raw_speedup": candidate["raw_speedup"] if candidate else None,
        "reference_speedup": reference_speedup,
        "reference_beaten": candidate["raw_speedup"] > reference_speedup if candidate else None,
        "median_seconds": candidate["medians"] if candidate else None,
        "model_calls": 0, "model_cost": None,
        "model_note": "Candidate was generated by a sub-agent, then supplied through fixed role responses; this is not a live ModelClient or token-cost test.",
        "scorer_note": "Real correctness and alternating timing; pilot scorer lacks the production sandbox and anti-cheat controls.",
        "normalization_note": "The candidate beat this pilot's independent simple reference, so normalized score is not a credible ceiling; use raw speedup for the pilot conclusion.",
    }
    atomic_json(run_dir / "pilot_report.json", report)
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=2500)
    parser.add_argument("--repetitions", type=int, default=7)
    args = parser.parse_args()
    print(json.dumps(run_pilot(size=args.size, repetitions=args.repetitions), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
